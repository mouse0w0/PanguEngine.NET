namespace PanguEngine.Client.UI.Controls;

/// <summary>
/// Specifies where a <see cref="TabView"/> places its tab strip relative to the content area.
/// </summary>
public enum TabStripPlacement
{
    /// <summary>The tab strip is placed above the content area.</summary>
    Top,

    /// <summary>The tab strip is placed below the content area.</summary>
    Bottom,

    /// <summary>The tab strip is placed to the left of the content area.</summary>
    Left,

    /// <summary>The tab strip is placed to the right of the content area.</summary>
    Right
}
