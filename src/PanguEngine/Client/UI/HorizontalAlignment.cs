namespace PanguEngine.Client.UI;

/// <summary>
/// Specifies horizontal positioning within an allocated layout slot.
/// </summary>
public enum HorizontalAlignment
{
    /// <summary>Positions the element at the left edge.</summary>
    Left,

    /// <summary>Positions the element at the horizontal center.</summary>
    Center,

    /// <summary>Positions the element at the right edge.</summary>
    Right,

    /// <summary>Stretches an automatically sized element across the available width.</summary>
    Stretch
}
