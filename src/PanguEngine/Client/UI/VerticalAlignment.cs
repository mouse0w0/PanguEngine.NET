namespace PanguEngine.Client.UI;

/// <summary>
/// Specifies vertical positioning within an allocated layout slot.
/// </summary>
public enum VerticalAlignment
{
    /// <summary>Positions the element at the top edge.</summary>
    Top,

    /// <summary>Positions the element at the vertical center.</summary>
    Center,

    /// <summary>Positions the element at the bottom edge.</summary>
    Bottom,

    /// <summary>Stretches an automatically sized element across the available height.</summary>
    Stretch
}
