namespace PanguEngine.Graphics;

/// <summary>
/// Identifies the format of a vertex attribute.
/// </summary>
public enum VertexAttributeFormat
{
    /// <summary>
    /// Two 32-bit floating point components.
    /// </summary>
    Float32x2,

    /// <summary>
    /// Three 32-bit floating point components.
    /// </summary>
    Float32x3,

    /// <summary>
    /// Four 32-bit floating point components.
    /// </summary>
    Float32x4,

    /// <summary>
    /// A single 32-bit unsigned integer component.
    /// </summary>
    UInt32
}