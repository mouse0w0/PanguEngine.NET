namespace PanguEngine.Graphics;

/// <summary>
/// Describes the dimensional shape of a texture resource.
/// </summary>
public enum TextureDimension
{
    /// <summary>
    /// A one-dimensional texture.
    /// </summary>
    Type1D,

    /// <summary>
    /// A two-dimensional texture.
    /// </summary>
    Type2D,

    /// <summary>
    /// A three-dimensional texture.
    /// </summary>
    Type3D
}